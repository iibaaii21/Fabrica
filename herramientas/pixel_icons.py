def icon(name, art, variants=False):
    rows = [r for r in art.strip('\n').split('\n')]
    rows = [(r + '.' * 16)[:16] for r in rows] + ['.' * 16] * (16 - len(rows))
    assert len(rows) == 16, name
    I[name] = (rows, variants)


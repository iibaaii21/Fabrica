def color_of(ch, level):
    return RAMPS[ch.lower()][level]


def render(rows, sub=None):
    """Devuelve imagen RGBA 16x16."""
    g = [list(r) for r in rows]
    if sub:
        g = [[(sub if c == 'v' else sub.upper() if c == 'V' else c) for c in r] for r in g]
    H = len(g); W = 16
    img = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
    px = img.load()

    def at(x, y):
        if 0 <= x < W and 0 <= y < H: return g[y][x]
        return '.'

    def ramp(c):
        return c.lower() if c.lower() in RAMPS else c

    filled = lambda c: c != '.'
    for y in range(H):
        for x in range(W):
            c = g[y][x]
            if c == '.': continue
            if c == '#': px[x, y] = hexc(OUTLINE); continue
            if c == '*': px[x, y] = hexc(WHITE); continue
            if c.isupper():
                px[x, y] = hexc(color_of(c, 2)); continue
            r = ramp(c)
            def edge(n):
                return n == '.' or (n not in '*' and ramp(n) != r)
            tl = edge(at(x, y - 1)) or edge(at(x - 1, y))
            br = edge(at(x, y + 1)) or edge(at(x + 1, y))
            if br and not tl: lvl = 2
            elif tl and not br: lvl = 0
            else: lvl = 1
            px[x, y] = hexc(color_of(c, lvl))
    # contorno automático (4 vecinos) alrededor de lo pintado
    base = img.copy(); bp = base.load()
    for y in range(16):
        for x in range(16):
            if bp[x, y][3] == 0:
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    nx, ny = x + dx, y + dy
                    if 0 <= nx < 16 and 0 <= ny < 16 and bp[nx, ny][3] > 0:
                        px[x, y] = hexc(OUTLINE); break
    return img


def hexc(h):
    h = h.lstrip('#'); return (int(h[0:2], 16), int(h[2:4], 16), int(h[4:6], 16), 255)


def all_icons():
    out = []
    for name, (rows, var) in I.items():
        if var:
            for vn, vc in VARIANTS.items():
                out.append((f'{name}_{vn}', render(rows, vc)))
        else:
            out.append((name, render(rows)))
    return out


